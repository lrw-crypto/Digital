function getDigitalLesson(question) {
  const written = window.DIGITAL_LESSONS[question.id];
  if (written) return written;

  const stem = question.stem.replace(/\s+/g, " ");
  const answer = question.options["ABCD".indexOf(question.answer)].replace(/\s+/g, " ").trim();
  const topic = digitalTopics.find(([pattern]) => pattern.test(stem)) ||
    digitalTopics.find(([pattern]) => pattern.test(answer));
  const polarity = stem.match(/(?:何者|哪(?:一個|一項|個|項)?|哪些)[^。？?]{0,18}(?:錯誤|不正確|不恰當|不符合|不是|不適合|不能)|(?:最不|並非|不屬於|不包含)[^。？?]{0,20}[？?]/);
  const steps = [topic ? topic[2] : digitalUnits[question.unit]];
  if (polarity) steps.push("題目要找不符合條件的敘述。先用同一個規則逐項檢查，再選出例外。");

  const notes = (question.official || "").trim()
    .split(/\n(?=\s*(?:[（(][A-D][）)]|[①-⑩]))/);
  const distractors = {};
  for (const block of notes) {
    const trimmed = block.trim();
    if (!trimmed) continue;
    const label = trimmed.match(/^(?:[（(][A-D][）)]\s*)+/);
    if (!label) {
      steps.push(...trimmed.split(/(?<=。)\s*/).filter(Boolean));
      continue;
    }
    const letters = label[0].match(/[A-D]/g);
    const reason = trimmed.slice(label[0].length).trim();
    if (!reason) continue;
    if (letters.includes(question.answer)) steps.push(`選項 ${question.answer} 的判斷依據：${reason}`);
    for (const letter of letters) {
      if (letter !== question.answer) distractors[letter] = distractors[letter] ? distractors[letter] + "\n" + reason : reason;
    }
  }

  const comparisons = Object.entries(distractors);
  if (comparisons.length) {
    steps.push("用下面的「選項比對」檢查各敘述。做錯時，先找你選的那一項和原則差在哪裡。");
  }
  const option = answer && !question.scan ? `「${answer}」` : "";
  steps.push(polarity
    ? `依本題的作答方向，應選 ${question.answer}${option}。`
    : `把上述判斷帶回題目，對應原卷答案 ${question.answer}${option}。`);
  return { concept: topic ? topic[1] : question.unit, steps, pitfalls: topic?.[3], distractors };
}
